'use strict';

// Inserts one finished, fake "DEMO" session (CPU + GPU run together, with ~1 sample/sec
// telemetry) straight into the database so the dashboard has something to show.
//   npm run seed:demo
// Re-running adds another demo session; delete rows with customer_name = 'DEMO (fake data)'.
require('dotenv').config();
const pool = require('../db/pool');
const { loadConfig } = require('../src/config');
const { computeResult } = require('../src/lib/resultComputation');
const { createTechnician } = require('../src/lib/technicians');

const DURATION_S = 600;

function wave(t, base, amp, noise, rampS) {
  const ramp = Math.min(1, t / rampS);
  return base + amp * ramp + (Math.random() - 0.5) * noise;
}

async function main() {
  const config = loadConfig();
  const serial = 'DEMO-' + Math.random().toString(36).slice(2, 8).toUpperCase();
  const end = Date.now() - 5 * 60 * 1000;
  const start = end - DURATION_S * 1000;

  let tech = (await pool.query('SELECT id FROM technicians WHERE active ORDER BY created_at LIMIT 1')).rows[0];
  if (!tech) {
    const created = await createTechnician('Demo Technician');
    tech = { id: created.id || created.technician?.id };
  }

  const client = await pool.connect();
  try {
    await client.query('BEGIN');
    await client.query('INSERT INTO machines (mobo_serial) VALUES ($1)', [serial]);
    const s = (await client.query(
      `INSERT INTO sessions (mobo_serial, technician_id, customer_name, session_type, notes, ssd_serials, other_serials, started_at, ended_at)
       VALUES ($1,$2,'DEMO (fake data)','new_build','Generated by scripts/seed-demo-session.js','["DEMO-SSD-0001"]','{"gpu":"DEMO-GPU-0001"}',$3,$4) RETURNING id`,
      [serial, tech.id, new Date(start), new Date(end)]
    )).rows[0];

    const runs = [
      {
        component: 'cpu',
        sensors: {
          cpu_package_temp_c: (t) => wave(t, 42, 40, 3, 60),
          cpu_load_pct: (t) => wave(t, 4, 95, 2, 5),
          cpu_clock_mhz: (t) => wave(t, 4900, -350, 60, 90),
          cpu_package_power_w: (t) => wave(t, 25, 105, 4, 20),
          cpu_fan_rpm: (t) => wave(t, 900, 1500, 40, 120),
        },
        stats: { max_temp_c: 83.6, avg_load_pct: 98.7, error_count: 0 },
        out: 'Prime95 (demo) -- Self-test passed, 0 errors, 0 warnings.',
      },
      {
        component: 'gpu',
        sensors: {
          gpu_temp_c: (t) => wave(t, 38, 36, 2, 90),
          gpu_load_pct: (t) => wave(t, 2, 97, 2, 5),
          gpu_power_w: (t) => wave(t, 30, 280, 6, 10),
          gpu_fan_rpm: (t) => wave(t, 800, 1700, 50, 100),
        },
        stats: { max_temp_c: 74.2, avg_load_pct: 98.1 },
        out: 'FurMark (demo) -- 10 min burn-in complete, no artifacts.',
      },
    ];

    for (const r of runs) {
      const cfg = config[r.component] || {};
      const { result } = computeResult(r.component, config, r.stats, null);
      const run = (await client.query(
        `INSERT INTO test_runs (session_id, component, config_snapshot, started_at, ended_at, tool_exit_code, tool_output_raw, summary_stats, result)
         VALUES ($1,$2,$3,$4,$5,0,$6,$7,$8) RETURNING id`,
        [s.id, r.component, JSON.stringify(cfg), new Date(start), new Date(end), r.out, JSON.stringify(r.stats), result]
      )).rows[0];

      const ids = [], ts = [], names = [], vals = [];
      for (let t = 0; t < DURATION_S; t++) {
        for (const [name, fn] of Object.entries(r.sensors)) {
          ids.push(run.id);
          ts.push(new Date(start + t * 1000));
          names.push(name);
          vals.push(Math.round(fn(t) * 10) / 10);
        }
      }
      await client.query(
        `INSERT INTO telemetry (test_run_id, ts, sensor_name, value)
         SELECT * FROM unnest($1::uuid[], $2::timestamptz[], $3::text[], $4::float8[])`,
        [ids, ts, names, vals]
      );
      console.log(`${r.component}: ${result}, ${ids.length} samples`);
    }
    await client.query('COMMIT');
    console.log(`Demo session ${s.id} (mobo ${serial})`);
  } catch (e) {
    await client.query('ROLLBACK');
    throw e;
  } finally {
    client.release();
    await pool.end();
  }
}

main().catch((e) => { console.error(e); process.exit(1); });
